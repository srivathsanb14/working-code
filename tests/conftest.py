    from discovery import contract
    from discovery import selftest as st
    from discovery.episodes import Episode
    mod, _ = contract.load_closedform(st.TRUTH_SRC)
    rng = np.random.default_rng(0); eps = []
    for k in range(2):
        inp = st.synthetic_inputs(toy_geo, 600, rng)
        e = Episode(name=f"toy_{k}", building=f"toy{k}", weather="w", policy="p", scenario=f"toy{k}/w", geo=toy_geo, inputs=inp,
                    T_meas=np.zeros((600, toy_geo["V"])))
        e.T_meas = cf.rollout(mod, mod.prepare(toy_geo, U), cf.Prepared(e, mod.HISTORY), U, [0], 600)[0]
        eps.append(e)
    return eps
