"""Append (or refresh) Appendix A in STATE_SPACE.md: every observation/action entry of train_8."""
import csv
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent; OUT = ROOT / "outputs"; MD = ROOT / "STATE_SPACE.md"
MARK = "\n## Appendix E. Every entry of the train_8 vectors"
text = MD.read_text(); text = text[:text.index(MARK)] if MARK in text else text.rstrip("\n") + "\n"
b = "building_train_8"
o = ["", MARK.strip(), "", "Generated by `code/build_appendix.py` from the environment's own field names and `outputs/building_train_8_*_annotated.csv`. `idx` is the position in the vector.", "",
     "### E.1 Observation vector (283 entries)", "", "| idx | field | role | in dynamics model? | units as delivered | meaning |", "|---|---|---|---|---|---|"]
for r in csv.DictReader(open(OUT / f"{b}_observation_annotated.csv")):
    o.append(f"| {r['index']} | `{r['field_id']}` | {r['role']} | {r['use_in_dynamics_model']} | {r['units_as_delivered']} | {r['meaning']} |")
o += ["", "### E.2 Action vector (75 entries; discrete part and continuous part are separate arrays, `idx` is within each part)", "", "| part | idx | device | setpoint | role | meaning |", "|---|---|---|---|---|---|"]
for r in csv.DictReader(open(OUT / f"{b}_action_annotated.csv")):
    o.append(f"| {r['kind']} | {r['kind_index']} | {r['device_id']} | `{r['setpoint_name']}` | {r['role']} | {r['meaning']} |")
MD.write_text(text + "\n".join(o) + "\n")
print("appendix written,", len(o), "lines")
